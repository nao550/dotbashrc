# ~/.shellrc.d/70-zshrc.sh
# Zsh 固有設定。

# =============================================================================
# コマンド履歴
# =============================================================================

HISTFILE="$HOME/.zsh_history"

# Zsh は履歴ファイルへ保存する件数以上をメモリ上に保持する必要があるため、
# 共通の保存件数を HISTSIZE / SAVEHIST の両方へ使用する。
HISTSIZE=${SHELL_HISTORY_FILE_SIZE:-50000}
SAVEHIST=${SHELL_HISTORY_FILE_SIZE:-50000}

# 行頭スペースのコマンドと直前と同じコマンドを履歴に残さない。
setopt HIST_IGNORE_SPACE
setopt HIST_IGNORE_DUPS

# 複数 Zsh 間で履歴を共有する。
setopt APPEND_HISTORY
setopt SHARE_HISTORY

# =============================================================================
# プロンプト
# =============================================================================

# Bash 側に近い user@host:directory の表示にする。
autoload -Uz colors && colors
PROMPT='%F{green}%n@%m%f:%F{blue}%~%f%# '

# =============================================================================
# 補完
# =============================================================================

autoload -Uz compinit
compinit
